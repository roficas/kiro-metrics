/** Wrap page content in a complete, self-contained HTML document. */
function page(title: string, metaLines: string[], body: string): string {
  const meta = metaLines
    .map((line) => `      <p class="meta">${line}</p>`)
    .join("\n");

  return `<!DOCTYPE html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${escapeHtml(title)}</title>
    <style>${STYLES}</style>
  </head>
  <body>
    <main>
      <h1>${escapeHtml(title)}</h1>
${meta}
${body}
      <footer>Generated by kiro-metrics from git commit attribution data.</footer>
    </main>
  </body>
</html>`;
}

function formatPeriod(period: { since: string; until: string }): string {
  return `${escapeHtml(period.since.slice(0, 10))} to ${escapeHtml(period.until.slice(0, 10))}`;
}

/** A metric card. `value` and `sub` must already be escaped or numeric. */
function card(label: string, value: string, sub?: string): string {
  const subHtml = sub ? `<span class="sub">${sub}</span>` : "";
  return `        <div class="card">
          <dt>${escapeHtml(label)}</dt>
          <dd>${value}${subHtml}</dd>
        </div>`;
}

function cards(items: string[]): string {
  return `      <dl class="cards">\n${items.join("\n")}\n      </dl>`;
}

/** Percentage bar. Decorative only — the numeric value is always rendered as text too. */
function bar(rate: number): string {
  const clamped = Math.max(0, Math.min(100, rate));
  return `<span class="bar" aria-hidden="true"><span style="width: ${clamped}%"></span></span>`;
}

interface TableSpec {
  caption: string;
  headers: Array<{ label: string; numeric?: boolean }>;
  /** Cell contents must already be escaped. */
  rows: Array<Array<{ html: string; numeric?: boolean; path?: boolean }>>;
}

function table({ caption, headers, rows }: TableSpec): string {
  const head = headers
    .map(
      (h) =>
        `<th scope="col"${h.numeric ? ' class="num"' : ""}>${escapeHtml(h.label)}</th>`
    )
    .join("");

  const body = rows
    .map((cells) => {
      const tds = cells
        .map((cell, index) => {
          const classes = [
            cell.numeric ? "num" : "",
            cell.path ? "path" : "",
          ]
            .filter(Boolean)
            .join(" ");
          const attr = classes ? ` class="${classes}"` : "";
          // First column acts as the row label for screen readers.
          const tag = index === 0 ? "th" : "td";
          const scope = index === 0 ? ' scope="row"' : "";
          return `<${tag}${scope}${attr}>${cell.html}</${tag}>`;
        })
        .join("");
      return `          <tr>${tds}</tr>`;
    })
    .join("\n");

  return `      <table>
        <caption>${escapeHtml(caption)}</caption>
        <thead>
          <tr>${head}</tr>
        </thead>
        <tbody>
${body}
        </tbody>
      </table>`;
}

export function formatDeveloperHtml(report: DeveloperReport): string {
  const sections: string[] = [];

  sections.push(
    cards([
      card("Total commits", String(report.commits.total)),
      card(
        "AI-involved commits",
        `${report.commits.involvementRate}%`,
        `${report.commits.aiInvolved} of ${report.commits.total} commits${bar(report.commits.involvementRate)}`
      ),
      card(
        "AI-authored lines",
        `${report.lines.authorshipRate}%`,
        `${report.lines.ai.toLocaleString()} of ${report.lines.total.toLocaleString()} lines${bar(report.lines.authorshipRate)}`
      ),
    ])
  );

  if (report.topAiFiles.length > 0) {
    sections.push("      <h2>Top AI-authored files</h2>");
    sections.push(
      table({
        caption: "Files ranked by share of AI-authored lines.",
        headers: [{ label: "File" }, { label: "AI authorship", numeric: true }],
        rows: report.topAiFiles.slice(0, 10).map((file) => [
          { html: escapeHtml(file.file), path: true },
          { html: `${file.authorshipRate}%`, numeric: true },
        ]),
      })
    );
  }

  const email = report.email ? ` (${escapeHtml(report.email)})` : "";

  return page(
    "AI Attribution Report — Developer View",
    [`Author: ${escapeHtml(report.author)}${email}`, `Period: ${formatPeriod(report.period)}`],
    sections.join("\n")
  );
}

export function formatTeamHtml(report: TeamReport): string {
  const sections: string[] = [];

  sections.push(
    cards([
      card(
        "AI code involvement rate",
        `${report.summary.involvementRate}%`,
        `${report.summary.aiInvolvedCommits} of ${report.summary.totalCommits} commits${bar(report.summary.involvementRate)}`
      ),
      card(
        "AI code authorship rate",
        `${report.summary.authorshipRate}%`,
        `share of lines${bar(report.summary.authorshipRate)}`
      ),
      card(
        "Delivery frequency",
        String(report.summary.deliveryFrequency),
        "commits per week"
      ),
      card("Total commits", String(report.summary.totalCommits)),
    ])
  );

  if (report.byAuthor.length > 0) {
    sections.push("      <h2>By author</h2>");
    sections.push(
      table({
        caption: "Per-contributor involvement and authorship rates.",
        headers: [
          { label: "Author" },
          { label: "Involvement", numeric: true },
          { label: "Authorship", numeric: true },
          { label: "Commits", numeric: true },
        ],
        rows: report.byAuthor.map((author) => [
          { html: escapeHtml(author.author) },
          { html: `${author.involvementRate}%`, numeric: true },
          { html: `${author.authorshipRate}%`, numeric: true },
          { html: String(author.commits), numeric: true },
        ]),
      })
    );
  }

  if (report.topAiFiles.length > 0) {
    sections.push("      <h2>Top AI-authored files</h2>");
    sections.push(
      table({
        caption: "Files ranked by share of AI-authored lines.",
        headers: [{ label: "File" }, { label: "AI authorship", numeric: true }],
        rows: report.topAiFiles.slice(0, 10).map((file) => [
          { html: escapeHtml(file.file), path: true },
          { html: `${file.authorshipRate}%`, numeric: true },
        ]),
      })
    );
  }

  if (report.weeklyTrend.length > 0) {
    sections.push("      <h2>Weekly trend</h2>");
    sections.push(
      table({
        caption: "Involvement and authorship rates by week.",
        headers: [
          { label: "Week starting" },
          { label: "Involvement", numeric: true },
          { label: "Authorship", numeric: true },
          { label: "Commits", numeric: true },
        ],
        rows: report.weeklyTrend.map((week) => [
          { html: escapeHtml(week.weekStart) },
          { html: `${week.involvementRate}%`, numeric: true },
          { html: `${week.authorshipRate}%`, numeric: true },
          { html: String(week.commitCount), numeric: true },
        ]),
      })
    );
  }

  return page(
    "AI Attribution Report — Team View",
    [`Period: ${formatPeriod(report.period)}`],
    sections.join("\n")
  );
}

export function formatBoardHtml(report: BoardReport): string {
  const sections: string[] = [];

  const headlineCards = [
    card(
      "AI code involvement",
      `${report.headline.involvementRate}%`,
      `of commits${bar(report.headline.involvementRate)}`
    ),
    card(
      "AI code authorship",
      `${report.headline.authorshipRate}%`,
      `of lines${bar(report.headline.authorshipRate)}`
    ),
    card(
      "Delivery frequency",
      String(report.headline.deliveryFrequency),
      "units per week"
    ),
  ];

  if (report.headline.ctsSwProxy !== undefined) {
    headlineCards.push(
      card(
        "CTS-SW proxy",
        `$${report.headline.ctsSwProxy}`,
        "per delivery unit"
      )
    );
  }

  sections.push(cards(headlineCards));

  const sign = (value: number): string => (value >= 0 ? "+" : "");
  sections.push("      <h2>Trend</h2>");
  sections.push(
    table({
      caption: "Change from the first week to the last week in the period.",
      headers: [{ label: "Metric" }, { label: "Change", numeric: true }],
      rows: [
        [
          { html: "Involvement" },
          {
            html: `${sign(report.trend.involvementChange)}${report.trend.involvementChange}pp`,
            numeric: true,
          },
        ],
        [
          { html: "Authorship" },
          {
            html: `${sign(report.trend.authorshipChange)}${report.trend.authorshipChange}pp`,
            numeric: true,
          },
        ],
      ],
    })
  );

  const status = report.guardrails.status;
  const notes = report.guardrails.notes
    .map((note) => `        <li>${escapeHtml(note)}</li>`)
    .join("\n");

  sections.push("      <h2>Guardrails</h2>");
  sections.push(
    `      <p><span class="badge ${status}">Status: ${escapeHtml(status)}</span></p>`
  );
  sections.push(`      <ul class="notes">\n${notes}\n      </ul>`);

  return page(
    "AI Metrics — Board Summary",
    [`Period: ${formatPeriod(report.period)}`],
    sections.join("\n")
  );
}
