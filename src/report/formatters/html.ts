/**
 * HTML formatter — outputs the report as a self-contained HTML document.
 *
 * The output is a complete page with inlined CSS and no external requests, so it can be
 * written to a file, attached to an email, or published as a static artifact from CI.
 * All interpolated values (author names, emails, file paths) come from git history and are
 * therefore untrusted, so every one of them is escaped before it reaches the markup.
 */

